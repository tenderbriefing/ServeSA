/**
 * Provision synthetic Firebase Auth identities for authenticated Playwright UAT.
 * Writes passwords to docs/reports/evidence/uat_tokens.env (gitignored).
 * Prefers email/password (ADC can set passwords). Custom tokens optional if SA signing available.
 * Does not print secret values. Requires ADC for project servesa-aad53.
 */
'use strict'

